// @desc    Update user profile or address
// @route   PUT /api/auth/profile
// @access  Private
export const updateProfile = async (req, res) => {
  try {
    const user = await User.findById(req.user._id);
    if (!user) return res.status(404).json({ message: 'User not found' });

    const { name, phone, address } = req.body;
    if (name) user.name = name;
    if (phone) user.phone = phone;

    if (address) {
      if (!user.addresses) user.addresses = [];
      // Add or set default
      const existingIdx = user.addresses.findIndex((a) => a.isDefault);
      if (existingIdx >= 0) {
        user.addresses[existingIdx] = { ...user.addresses[existingIdx].toObject(), ...address, isDefault: true };
      } else {
        user.addresses.push({ ...address, isDefault: true });
      }
    }

    await user.save();
    res.json({
      message: 'Profile updated successfully',
      user: {
        _id: user._id,
        name: user.name,
        email: user.email,
        role: user.role,
        avatar: user.avatar,
        phone: user.phone,
        addresses: user.addresses
      }
    });
  } catch (error) {
    res.status(500).json({ message: error.message });
  }
};
